package ai.ctrlb.mobile.media

import ai.ctrlb.mobile.domain.TimeRange
import android.content.Context
import android.opengl.GLES30
import androidx.media3.common.VideoFrameProcessingException
import androidx.media3.common.util.GlProgram
import androidx.media3.common.util.Size
import androidx.media3.common.util.UnstableApi
import androidx.media3.effect.BaseGlShaderProgram
import androidx.media3.effect.GlEffect
import androidx.media3.effect.GlShaderProgram

@UnstableApi
class DynamicShaderEffect(
    private val id: String,
    private val range: TimeRange,
    private val fragmentShader: String,
    private val uniforms: Map<String, Float>,
    private val onError: (String) -> Unit
) : GlEffect {
    override fun toGlShaderProgram(context: Context, useHdr: Boolean): GlShaderProgram {
        return try {
            DynamicShaderProgram(context, useHdr, fragmentShader, uniforms, range)
        } catch (e: Exception) {
            e.printStackTrace()
            onError(e.message ?: "Unknown compilation error")
            // Fallback to pass-through
            FallbackShaderProgram(context, useHdr)
        }
    }
}

@UnstableApi
class DynamicShaderProgram(
    context: Context,
    useHdr: Boolean,
    fragmentShader: String,
    private val uniforms: Map<String, Float>,
    private val range: TimeRange
) : BaseGlShaderProgram(useHdr, 1) {

    private val glProgram: GlProgram

    init {
        val vertexShader = """
            #version 300 es
            in vec4 aFramePosition;
            out vec2 vTexSamplingCoord;
            void main() {
              gl_Position = aFramePosition;
              vTexSamplingCoord = vec2((aFramePosition.x + 1.0) / 2.0, (aFramePosition.y + 1.0) / 2.0);
            }
        """.trimIndent()
        
        glProgram = GlProgram(vertexShader, fragmentShader)
    }

    override fun configure(inputWidth: Int, inputHeight: Int): Size = Size(inputWidth, inputHeight)

    override fun drawFrame(inputTexId: Int, presentationTimeUs: Long) {
        try {
            glProgram.use()
            
            // Pass the uniform variables generated by the AI
            for ((name, value) in uniforms) {
                try { glProgram.setFloatUniform(name, value) } catch (_: Exception) {}
            }
            
            // Pass time and progress
            val presentationMs = presentationTimeUs / 1000
            val progress = ((presentationMs - range.startMs).toFloat() / maxOf(1L, range.durationMs)).coerceIn(0f, 1f)
            
            try { glProgram.setFloatUniform("uTime", presentationMs.toFloat() / 1000f) } catch (_: Exception) {}
            try { glProgram.setFloatUniform("uProgress", progress) } catch (_: Exception) {}

            glProgram.setSamplerTexIdUniform("uTexSampler", inputTexId, 0)
            glProgram.setBufferAttribute("aFramePosition", floatArrayOf(-1f, -1f, 0f, 1f, 1f, -1f, 0f, 1f, -1f, 1f, 0f, 1f, 1f, 1f, 0f, 1f), 4)
            glProgram.bindAttributesAndUniforms()
            
            GLES30.glDrawArrays(GLES30.GL_TRIANGLE_STRIP, 0, 4)
        } catch (e: Exception) {
            throw VideoFrameProcessingException(e)
        }
    }
    
    override fun release() {
        super.release()
        try { glProgram.delete() } catch (_: Exception) {}
    }
}

@UnstableApi
class FallbackShaderProgram(
    context: Context,
    useHdr: Boolean
) : BaseGlShaderProgram(useHdr, 1) {
    
    private val glProgram: GlProgram

    init {
        val vertexShader = """
            #version 300 es
            in vec4 aFramePosition;
            out vec2 vTexSamplingCoord;
            void main() {
              gl_Position = aFramePosition;
              vTexSamplingCoord = vec2((aFramePosition.x + 1.0) / 2.0, (aFramePosition.y + 1.0) / 2.0);
            }
        """.trimIndent()
        val fragmentShader = """
            #version 300 es
            precision mediump float;
            uniform sampler2D uTexSampler;
            in vec2 vTexSamplingCoord;
            out vec4 outColor;
            void main() {
              outColor = texture(uTexSampler, vTexSamplingCoord);
            }
        """.trimIndent()
        glProgram = GlProgram(vertexShader, fragmentShader)
    }

    override fun configure(inputWidth: Int, inputHeight: Int): Size = Size(inputWidth, inputHeight)

    override fun drawFrame(inputTexId: Int, presentationTimeUs: Long) {
        try {
            glProgram.use()
            glProgram.setSamplerTexIdUniform("uTexSampler", inputTexId, 0)
            glProgram.setBufferAttribute("aFramePosition", floatArrayOf(-1f, -1f, 0f, 1f, 1f, -1f, 0f, 1f, -1f, 1f, 0f, 1f, 1f, 1f, 0f, 1f), 4)
            glProgram.bindAttributesAndUniforms()
            GLES30.glDrawArrays(GLES30.GL_TRIANGLE_STRIP, 0, 4)
        } catch (e: Exception) {
            throw VideoFrameProcessingException(e)
        }
    }

    override fun release() {
        super.release()
        try { glProgram.delete() } catch (_: Exception) {}
    }
}
